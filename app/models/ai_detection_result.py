"""
AIDetectionResult SQLAlchemy ORM Model.

Stores estimated AI-generated-text likelihood and model metadata for an article.
Important Note: AI detection likelihood is a statistical estimate based on language
modeling heuristics (e.g. perplexity, burstiness), NOT definitive proof that an article
was generated by AI.
"""

from datetime import datetime, timezone
from sqlalchemy import Column, Integer, String, Float, Boolean, Text, DateTime, ForeignKey, CheckConstraint
from sqlalchemy.orm import relationship
from sqlalchemy.sql import func

from app.db.base import Base


class AIDetectionResult(Base):
    """
    AI_DETECTION_RESULT Table.
    Stores automated probabilistic estimates of machine-generated text.
    """

    __tablename__ = "ai_detection_results"

    id = Column(Integer, primary_key=True, index=True)
    article_id = Column(
        Integer,
        ForeignKey("articles.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    # Statistical likelihood estimate (0.0 to 1.0)
    ai_likelihood = Column(Float, nullable=False)

    # Name and version of the detector model (e.g., 'roberta-base-openai-detector')
    model_name = Column(String(100), nullable=False)
    model_version = Column(String(50), nullable=True)

    # Detailed features (e.g., perplexity, burstiness metrics, segment scores)
    analysis_details = Column(Text, nullable=True)

    # Model confidence in this estimation (0.0 to 1.0)
    confidence_score = Column(Float, nullable=True)

    # Flag for human editorial review
    is_flagged_for_review = Column(Boolean, default=False, nullable=False)

    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    __table_args__ = (
        CheckConstraint(
            "ai_likelihood >= 0.0 AND ai_likelihood <= 1.0",
            name="ck_ai_detection_results_likelihood_range",
        ),
    )

    article = relationship("Article", back_populates="ai_detection_results")

    def __repr__(self) -> str:
        return (
            f"<AIDetectionResult(id={self.id}, article_id={self.article_id}, "
            f"likelihood={self.ai_likelihood:.2f}, model='{self.model_name}')>"
        )
